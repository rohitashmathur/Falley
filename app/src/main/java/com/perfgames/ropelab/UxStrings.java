    public static String text(int language,String english,Object...args){
        if(english==null)return "";
        String[] row=STRINGS.get(english);
        if(row==null||language!=FalleyStrings.HINDI&&language!=FalleyStrings.INDONESIAN)return ExpansionStrings.text(language,english,args);
        String value=row[language==FalleyStrings.HINDI?0:1];
        if(args==null||args.length==0)return value;
        try{return String.format(Locale.US,value,args);}catch(IllegalFormatException invalid){return ExpansionStrings.text(language,english,args);}
    }
    private static void add(String en,String hi,String id){STRINGS.put(en,new String[]{hi,id});}
